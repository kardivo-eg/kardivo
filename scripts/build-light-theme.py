#!/usr/bin/env python3
"""Builds the light-theme block at the end of public/styles.css.

Kardivo's stylesheet is written for dark. This script reads every colour in it, works out
what role the colour plays (page/card background, text, border, shadow) and writes matching
light-theme overrides under html[data-theme="light"]. Re-run it after you change the dark
styles:   python3 scripts/build-light-theme.py
Hand-made light fixes live in the block after the HAND-FIXES marker and are kept.
"""
import colorsys, re, sys, pathlib
import tinycss2

CSS = pathlib.Path(__file__).resolve().parent.parent / "public" / "styles.css"
START = "/* ==== LIGHT THEME (generated by scripts/build-light-theme.py) ==== */"
HAND = "/* ==== LIGHT THEME HAND-FIXES ==== */"

HEX = re.compile(r"#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{3}\b")


def parse_hex(h):
    h = h[1:]
    if len(h) in (3, 4):
        h = "".join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
    return r, g, b, a


def fmt(r, g, b, a):
    r, g, b = (max(0, min(255, round(x))) for x in (r, g, b))
    if a >= 0.995:
        return "#%02x%02x%02x" % (r, g, b)
    return "rgba(%d,%d,%d,%.3f)" % (r, g, b, max(0, min(1, a)))


def hls(r, g, b):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    return h, l * 100, s


def vsat(r, g, b):
    """How colourful it looks (0 = grey, 1 = fully saturated)."""
    return (max(r, g, b) - min(r, g, b)) / max(max(r, g, b), 1)


def is_black(r, g, b):
    return max(r, g, b) < 14 and max(r, g, b) - min(r, g, b) <= 2


def from_hls(h, l, s, a):
    r, g, b = colorsys.hls_to_rgb(h, max(0, min(100, l)) / 100, max(0, min(1, s)))
    return fmt(r * 255, g * 255, b * 255, a)


def is_accent_solid(c):
    r, g, b, a = c
    h, l, s = hls(r, g, b)
    return a >= 0.85 and 25 <= l <= 85 and vsat(r, g, b) > 0.3


def map_bg(c):
    r, g, b, a = c
    h, l, s = hls(r, g, b)
    if is_black(r, g, b):                       # pure black scrims stay
        return None
    if min(r, g, b) >= 240 and a < 0.995:       # white overlay -> dark overlay
        return fmt(40, 25, 90, min(0.4, a * 1.6))
    if l > 25:                                  # accents and light colours stay
        return None
    if l <= 12:
        nl = 94 + l * 0.4
    else:
        nl = 98 - (l - 12) * 1.1
    return from_hls(h, nl, min(s, 0.45), a)


def map_text(c):
    r, g, b, a = c
    h, l, s = hls(r, g, b)
    if l < 40:
        return None
    if vsat(r, g, b) > 0.2:
        return from_hls(h, 42, min(s, 0.7), a)
    return from_hls(h, min((100 - l) * 0.8 + 14, 46), min(s, 0.2), a)


def map_border(c):
    r, g, b, a = c
    h, l, s = hls(r, g, b)
    if is_black(r, g, b):
        return None
    if min(r, g, b) >= 240 and a < 0.995:
        return fmt(40, 25, 90, min(0.35, a * 2))
    if l >= 45:
        return None
    return from_hls(h, 100 - l * 0.7, min(s, 0.35), a)


def map_shadow(c):
    r, g, b, a = c
    h, l, s = hls(r, g, b)
    if is_black(r, g, b):
        return fmt(60, 40, 110, a * 0.32)
    return None


def prop_role(name):
    n = name.lower()
    if n in ("background", "background-color", "background-image"):
        return "bg"
    if n in ("color", "fill", "stroke", "caret-color", "-webkit-text-fill-color", "text-decoration-color"):
        return "text"
    if n.startswith("border") or n.startswith("outline") or n == "column-rule":
        return "border"
    if n in ("box-shadow", "text-shadow", "filter", "backdrop-filter"):
        return "shadow"
    custom = {"--bg": "bg", "--panel": "bg", "--panel2": "bg", "--line": "border", "--line-soft": "border",
              "--text": "text", "--muted": "text", "--muted-2": "text", "--shadow": "shadow"}
    return custom.get(n)


MAPPERS = {"bg": map_bg, "text": map_text, "border": map_border, "shadow": map_shadow}


def transform(value, role):
    out, last, changed = [], 0, False
    for m in HEX.finditer(value):
        # leave colours inside url(...) alone
        if value.rfind("url(", 0, m.start()) > value.rfind(")", 0, m.start()):
            continue
        new = MAPPERS[role](parse_hex(m.group()))
        if new:
            out.append(value[last:m.start()])
            out.append(new)
            last = m.end()
            changed = True
    out.append(value[last:])
    return "".join(out), changed


def rule_has_accent_bg(decls):
    for d in decls:
        if d.type != "declaration" or prop_role(d.name) != "bg":
            continue
        v = tinycss2.serialize(d.value)
        if "var(--accent" in v or "var(--purple" in v:
            return True
        for m in HEX.finditer(v):
            if is_accent_solid(parse_hex(m.group())):
                return True
    return False


def light_selector(sel):
    sel = sel.strip()
    # :where() adds no specificity, so every light rule ranks exactly like the dark rule it mirrors
    if sel.startswith(":root"):
        return ':root:where([data-theme="light"])' + sel[5:]
    if re.match(r"html\b", sel):
        return 'html:where([data-theme="light"])' + sel[4:]
    return ':where(html[data-theme="light"]) ' + sel


def split_selectors(prelude):
    parts, depth, cur = [], 0, ""
    for ch in tinycss2.serialize(prelude):
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [p for p in parts if p.strip()]


COUNTER = [0]


def collect_last(rules, ctx, last):
    for r in rules:
        if r.type == "qualified-rule":
            COUNTER[0] += 1
            sel = tinycss2.serialize(r.prelude).strip()
            for d in tinycss2.parse_declaration_list(r.content, skip_comments=True, skip_whitespace=True):
                if d.type == "declaration":
                    last[(ctx, sel, d.name)] = COUNTER[0]
        elif r.type == "at-rule" and r.lower_at_keyword in ("media", "supports") and r.content:
            collect_last(tinycss2.parse_rule_list(r.content, skip_comments=True, skip_whitespace=True),
                         ctx + "|" + tinycss2.serialize(r.prelude).strip(), last)


def process_rules(rules, ctx="", last=None):
    out = []
    for r in rules:
        if r.type == "qualified-rule":
            COUNTER[0] += 1
            my_no = COUNTER[0]
            decls = tinycss2.parse_declaration_list(r.content, skip_comments=True, skip_whitespace=True)
            skip_text = rule_has_accent_bg(decls)
            lines = []
            sel_key = tinycss2.serialize(r.prelude).strip()
            for d in decls:
                if d.type != "declaration":
                    continue
                if last is not None and last.get((ctx, sel_key, d.name)) != my_no:
                    continue            # a later rule with the same selector overrides this one anyway
                role = prop_role(d.name)
                if not role or (role == "text" and skip_text):
                    continue
                new, changed = transform(tinycss2.serialize(d.value), role)
                if changed:
                    lines.append("%s:%s%s" % (d.name, new.strip(), "!important" if d.important else ""))
            if lines:
                sels = ",".join(light_selector(s) for s in split_selectors(r.prelude))
                out.append("%s{%s}" % (sels, ";".join(lines)))
        elif r.type == "at-rule" and r.lower_at_keyword in ("media", "supports") and r.content:
            inner = process_rules(tinycss2.parse_rule_list(r.content, skip_comments=True, skip_whitespace=True),
                                  ctx + "|" + tinycss2.serialize(r.prelude).strip(), last)
            if inner:
                out.append("@%s %s{%s}" % (r.at_keyword, tinycss2.serialize(r.prelude).strip(), "\n".join(inner)))
    return out


def main():
    text = CSS.read_text(encoding="utf-8")
    hand = ""
    if HAND in text:
        hand = text[text.index(HAND):]
    if START in text:
        text = text[:text.index(START)]
    elif HAND in text:
        text = text[:text.index(HAND)]
    text = text.rstrip() + "\n"
    rules = tinycss2.parse_stylesheet(text, skip_comments=True, skip_whitespace=True)
    last = {}
    COUNTER[0] = 0
    collect_last(rules, "", last)
    COUNTER[0] = 0
    block = process_rules(rules, "", last)
    result = text + "\n" + START + "\n:root{color-scheme:dark}\n:root[data-theme=\"light\"]{color-scheme:light}\n" + "\n".join(block) + "\n"
    if hand:
        result += "\n" + hand
    CSS.write_text(result, encoding="utf-8")
    print("wrote %d light rules" % len(block), file=sys.stderr)


if __name__ == "__main__":
    main()
