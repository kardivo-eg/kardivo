// Self-host Inter, Cairo and Exo 2. Run once from the project root with internet access:
//   node scripts/self-host-fonts.mjs
// It downloads the woff2 files into public/fonts/, writes public/fonts.css, and swaps the Google Fonts
// tags in public/index.html for a preload plus /fonts.css. Deploy afterwards.
import { mkdir, writeFile, readFile } from "node:fs/promises";

const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&family=Cairo:wght@400;500;600;700;800&family=Exo+2:wght@800&display=swap";
// Google serves woff2 only to modern user agents.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const css = await (await fetch(CSS_URL, { headers: { "user-agent": UA } })).text();
await mkdir("public/fonts", { recursive: true });

const blocks = css.match(/(\/\*[^*]*\*\/\s*)?@font-face\s*\{[^}]*\}/g) || [];
if (!blocks.length) throw new Error("No @font-face blocks came back from Google Fonts.");
const seen = new Map();
let out = "/* Self-hosted fonts (generated by scripts/self-host-fonts.mjs) */\n";
let n = 0;
for (const b of blocks) {
  const subset = (b.match(/\/\*\s*([\w-]+)\s*\*\//) || [])[1] || "x";
  const family = (b.match(/font-family:\s*'([^']+)'/) || [])[1].replace(/\s+/g, "");
  const weight = (b.match(/font-weight:\s*(\d+)/) || [])[1];
  const url = (b.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
  if (!url) continue;
  const file = `${family}-${weight}-${subset}.woff2`;
  if (!seen.has(url)) {
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    await writeFile(`public/fonts/${file}`, buf);
    seen.set(url, file);
    n++;
  }
  out += b.replace(/\/\*[^*]*\*\/\s*/, "").replace(url, `/fonts/${seen.get(url)}`) + "\n";
}
await writeFile("public/fonts.css", out);

const files = [...seen.values()];
const pick = (re) => files.find((f) => re.test(f));
const preloads = [pick(/^Cairo-.*-arabic\.woff2$/), pick(/^Inter-.*-latin\.woff2$/)]
  .filter(Boolean)
  .map((f) => `<link rel="preload" href="/fonts/${f}" as="font" type="font/woff2" crossorigin>`)
  .join("");

let html = await readFile("public/index.html", "utf8");
const before = html;
html = html
  .replace(/<link rel="preconnect" href="https:\/\/fonts\.googleapis\.com">/, "")
  .replace(/<link rel="preconnect" href="https:\/\/fonts\.gstatic\.com" crossorigin>/, "")
  .replace(
    /<link href="https:\/\/fonts\.googleapis\.com\/css2[^>]*rel="stylesheet">/,
    `${preloads}<link rel="stylesheet" href="/fonts.css?v=1">`,
  );
if (html === before) console.warn("index.html was not changed (already converted?).");
await writeFile("public/index.html", html);
console.log(`Done: ${n} font files, public/fonts.css written, index.html updated.`);
